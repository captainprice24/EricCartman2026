// Replace the 141 retired Easy series; never relabel their unchanged reasoning.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import {generateUpgradePatterns} from './abstract-patterns.mjs';
import {generateHardAbstract} from './abstract-hard.mjs';
import {alternatives} from './abstract-transfer-review.mjs';
import {abstractSetSource} from '../lib/abstract-format.mjs';
import {abstractRubric} from '../lib/abstract-difficulty.mjs';
import {decode,predictions} from '../../tests/abstract-challenge-solver.mjs';
const same=(a,b)=>JSON.stringify(a)===JSON.stringify(b);
const hash=q=>crypto.createHash('sha256').update(JSON.stringify(q)).digest('hex');
export function upgradeEasyAbstract(root){
 const baseline=JSON.parse(fs.readFileSync(path.join(root,'scripts/generators/abstract-no-easy-baseline.json'))).items;
 const before=new Map(baseline.map(q=>[q.id,q]));
 const medium=generateUpgradePatterns(71), hard=generateHardAbstract(root,{count:70,accept:(sequence,key)=>{const p=predictions(sequence.map(decode));return p.length===1&&same(p[0],decode(key));}});
 const registryFile=path.join(root,'scripts/generators/abstract-no-easy-revisions.json');
 const recorded=fs.existsSync(registryFile)?JSON.parse(fs.readFileSync(registryFile)):null,revisions={};
 let n=0,m=0,h=0;
 for(let s=1;s<=4;s++){
  const file=path.join(root,`questions/abstract/abstract-set-${String(s).padStart(2,'0')}.js`);let set;
  vm.runInNewContext(fs.readFileSync(file,'utf8'),{EPSO_BANK:{registerSet:x=>set=x}});
  set.questions=set.questions.map(old=>{
   if(!same(old,before.get(old.id)))throw Error('Input changed before no-Easy review: '+old.id);
   if(old.difficulty!==1)return old;
   const isMedium=n++%2===0;
   let q={...(isMedium?medium[m++]:hard[h++]),id:old.id.replace(/-r3$/,'-r4'),supersedes:old.id};
   if(isMedium)q={...q,...alternatives(q,1000+m),reasoning:{...q.reasoning,pathReviewed:true}};
   // Preserve answer-position balance of each existing set and fixed-form slot.
   const options=q.options.slice(),notes=q.optionNotes.slice(),key=options.splice(q.answer,1)[0],note=notes.splice(q.answer,1)[0];
   options.splice(old.answer,0,key);notes.splice(old.answer,0,note);
   q={...q,options,optionNotes:notes,answer:old.answer};
   if(abstractRubric(q).level!==q.difficulty)throw Error('Upgrade band mismatch '+q.id);
   revisions[old.id]={id:q.id,beforeSha256:hash(old),sha256:hash(q),beforeDifficulty:1,difficulty:q.difficulty};
   return q;
  });
  set.version++;set.description='Original Medium and Hard series: spatial tracking, conditional transformations and dependent patterns. Worked solutions and progressive hints.';
  fs.writeFileSync(file,abstractSetSource(set,'Generated by scripts/generators/abstract.mjs; formerly Easy slots use new Medium/Hard content.'));
 }
 if(n!==141||m!==71||h!==70)throw Error('Unexpected upgrade totals');
 if(recorded&&!same(recorded.revisions,revisions))throw Error('Published upgrades changed: use new IDs');
 if(!recorded)fs.writeFileSync(registryFile,JSON.stringify({baseCommit:'6e38ebf',revisions},null,2)+'\n');
 console.log('Upgraded 141 Easy abstract items: 71 Medium, 70 Hard.');
}
